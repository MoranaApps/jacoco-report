def test_d1_unset_summary_variable_prints_the_not_set_warning(
    mocker: MockerFixture, make_report_file_coverage, monkeypatch, capsys
):
    monkeypatch.delenv("GITHUB_STEP_SUMMARY", raising=False)
    _run_all_unchanged(mocker, make_report_file_coverage)
    _set_target(mocker, "both")

    JaCoCoReport().run()

    expected = SUMMARY_NOT_SET_WARNING.format(target="both")
    assert f"::warning::{expected}" in capsys.readouterr().out


def test_d1_summary_warning_does_not_change_the_job_result(
    mocker: MockerFixture, make_report_file_coverage, monkeypatch, tmp_path
):
    monkeypatch.setenv("GITHUB_STEP_SUMMARY", str(tmp_path))  # a directory: the write fails
    _run_all_unchanged(mocker, make_report_file_coverage)
    _set_target(mocker, "summary")

    jr = JaCoCoReport()
    jr.run()

    assert jr.violations == []
    assert jr.has_operational_failure is False
    assert jr.total_overall_coverage_passed is True


def test_run_summary_target_prints_the_not_set_warning_and_no_comment_warning(
    mocker: MockerFixture, make_report_file_coverage, monkeypatch, capsys
):
    monkeypatch.delenv("GITHUB_STEP_SUMMARY", raising=False)
    changed = _report_with_changes("Report A", make_report_file_coverage)
    mocks = _make_run_mocks(mocker, skip_unchanged=False, evaluate_unchanged=True, reports=[changed])
    _set_target(mocker, "summary")

    JaCoCoReport().run()

    out = capsys.readouterr().out
    assert f"::warning::{SUMMARY_NOT_SET_WARNING.format(target='summary')}" in out
    assert "PR comment may not have been changed" not in out
    mocks["gh"].add_comment.assert_not_called()
