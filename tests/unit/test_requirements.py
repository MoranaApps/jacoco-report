import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
REQUIREMENTS_IN = REPO_ROOT / "requirements.in"
REQUIREMENTS_TXT = REPO_ROOT / "requirements.txt"
REQUIREMENTS_DEV = REPO_ROOT / "requirements-dev.txt"
PIN = re.compile(r"([A-Za-z0-9._-]+)==(\S+)")
SHA256_HASH = re.compile(r"--hash=sha256:[0-9a-f]{64}")
COMPILE_COMMAND = "#    pip-compile --generate-hashes --output-file=requirements.txt requirements.in"


def _lines(path):
    return [line.strip() for line in path.read_text(encoding="utf-8").splitlines()]


def _runtime_pins(path=REQUIREMENTS_IN):
    pins = {}
    for line in _lines(path):
        if not line or line.startswith("#"):
            continue
        match = PIN.fullmatch(line)
        assert match, f"{path.name} line is not a name==version pin: {line!r}"
        pins[match.group(1)] = match.group(2)
    return pins


def _lock_entries():
    # Each locked package starts with `name==version \`, followed by `--hash=` continuation lines and `# via` comments.
    entries = []
    for text in _lines(REQUIREMENTS_TXT):
        text = text.removesuffix("\\").strip()
        if not text or text.startswith("#"):
            continue
        if text.startswith("--hash="):
            entries[-1][1].append(text)
        else:
            entries.append((text, []))
    return entries


def test_lock_header_names_python_311_and_the_compile_command():
    text = REQUIREMENTS_TXT.read_text(encoding="utf-8")
    assert "This file is autogenerated by pip-compile with Python 3.11" in text
    assert COMPILE_COMMAND in text


def test_every_locked_package_is_pinned_and_has_a_sha256_hash():
    entries = _lock_entries()
    assert entries, "requirements.txt locks no packages"
    for requirement, hashes in entries:
        assert PIN.fullmatch(requirement), f"not a name==version pin: {requirement}"
        assert hashes, f"{requirement} has no --hash=sha256 entry"
        assert all(SHA256_HASH.fullmatch(text) for text in hashes), f"{requirement} has a malformed hash"


def test_every_runtime_pin_is_locked_at_the_same_version():
    locked = {PIN.fullmatch(requirement).groups() for requirement, _ in _lock_entries()}
    for name, version in _runtime_pins().items():
        assert (name, version) in locked, f"{name}=={version} from requirements.in is not in requirements.txt"


def test_dev_requirements_build_on_the_runtime_input():
    # `-r requirements.txt` would put the whole dev install into hash-checking mode and fail on the unhashed dev tools.
    assert _lines(REQUIREMENTS_DEV)[0] == "-r requirements.in"


def test_runtime_input_line_that_is_not_a_pin_fails_with_the_line_named(tmp_path):
    bad_input = tmp_path / "requirements.in"
    bad_input.write_text("requests>=2.34\n", encoding="utf-8")
    with pytest.raises(AssertionError, match=r"requests>=2\.34"):
        _runtime_pins(bad_input)
