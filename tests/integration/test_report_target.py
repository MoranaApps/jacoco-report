"""
Offline integration tests: report-target runs the whole pipeline, and the job summary holds the report.

GitHub is mocked. GITHUB_STEP_SUMMARY is a real file under tmp_path, as the runner sets it for a step.
"""

from __future__ import annotations

from pathlib import Path
from typing import cast
from unittest.mock import MagicMock

import pytest
from pytest_mock import MockerFixture

from tests.integration.helpers import TEST_PROJECT_GLOB, capture_run, make_env_base, mock_github_offline

_CHANGED_FILES = ["com/example/module_large/MidClass.java"]
_TITLE = "JaCoCo Coverage Report"
_COMMENT_CALLS = ("get_comments", "add_comment", "update_comment", "delete_comment")


def _comment_mocks(mocker: MockerFixture) -> dict[str, MagicMock]:
    """Patch the offline changed files and every comment call, so a test can assert which of them ran."""
    mock_github_offline(mocker, _CHANGED_FILES)
    mocks: dict[str, MagicMock] = {}
    for name in _COMMENT_CALLS:
        default: list[dict[str, object]] | bool = [] if name == "get_comments" else True
        mocks[name] = cast(MagicMock, mocker.patch(f"jacoco_report.utils.github.GitHub.{name}", return_value=default))
    return mocks


def test_summary_target_writes_the_report_title_to_the_job_summary(mocker: MockerFixture, tmp_path: Path) -> None:
    summary = tmp_path / "step_summary.md"
    _comment_mocks(mocker)

    result = capture_run(
        make_env_base(
            INPUT_REPORT_TARGET="summary",
            INPUT_UPDATE_COMMENT="true",
            GITHUB_STEP_SUMMARY=str(summary),
        )
    )

    assert result.exit_code == 0, result.stdout
    body = summary.read_text(encoding="utf-8")
    assert body.startswith(f"**{_TITLE}**")
    assert "| **Overall**" in body
    assert "Generated by [MoranaApps/jacoco-report]" in body


def test_summary_target_makes_no_comment_api_call(mocker: MockerFixture, tmp_path: Path) -> None:
    mocks = _comment_mocks(mocker)

    result = capture_run(
        make_env_base(
            INPUT_REPORT_TARGET="summary",
            INPUT_UPDATE_COMMENT="true",
            GITHUB_STEP_SUMMARY=str(tmp_path / "step_summary.md"),
        )
    )

    assert result.exit_code == 0, result.stdout
    for name in _COMMENT_CALLS:
        mocks[name].assert_not_called()


def test_summary_target_with_update_comment_false_also_makes_no_comment_call(
    mocker: MockerFixture, tmp_path: Path
) -> None:
    mocks = _comment_mocks(mocker)

    result = capture_run(
        make_env_base(
            INPUT_REPORT_TARGET="summary",
            INPUT_UPDATE_COMMENT="false",
            GITHUB_STEP_SUMMARY=str(tmp_path / "step_summary.md"),
        )
    )

    assert result.exit_code == 0, result.stdout
    for name in _COMMENT_CALLS:
        mocks[name].assert_not_called()


def test_both_target_writes_the_summary_and_the_comment(mocker: MockerFixture, tmp_path: Path) -> None:
    summary = tmp_path / "step_summary.md"
    mocks = _comment_mocks(mocker)

    result = capture_run(
        make_env_base(
            INPUT_REPORT_TARGET="both",
            INPUT_UPDATE_COMMENT="false",
            GITHUB_STEP_SUMMARY=str(summary),
        )
    )

    assert result.exit_code == 0, result.stdout
    assert summary.read_text(encoding="utf-8").startswith(f"**{_TITLE}**")
    mocks["add_comment"].assert_called_once()
    assert mocks["add_comment"].call_args[0][1] == summary.read_text(encoding="utf-8")


def test_comment_target_leaves_the_job_summary_alone(mocker: MockerFixture, tmp_path: Path) -> None:
    summary = tmp_path / "step_summary.md"
    _comment_mocks(mocker)

    result = capture_run(make_env_base(INPUT_REPORT_TARGET="comment", GITHUB_STEP_SUMMARY=str(summary)))

    assert result.exit_code == 0, result.stdout
    assert not summary.exists()


def test_summary_target_without_the_runner_variable_warns_and_keeps_the_job_result(
    mocker: MockerFixture,
) -> None:
    _comment_mocks(mocker)
    env = make_env_base(INPUT_REPORT_TARGET="summary")
    env.pop("GITHUB_STEP_SUMMARY", None)

    result = capture_run(env)

    assert result.exit_code == 0, result.stdout
    assert "::warning::report-target 'summary' writes to the job summary, but GITHUB_STEP_SUMMARY is not set" in (
        result.stdout
    )


@pytest.mark.parametrize("value", ["pr", "comments"])
def test_invalid_report_target_fails_validation(mocker: MockerFixture, tmp_path: Path, value: str) -> None:
    _comment_mocks(mocker)

    result = capture_run(make_env_base(INPUT_REPORT_TARGET=value, GITHUB_STEP_SUMMARY=str(tmp_path / "s.md")))

    assert result.exit_code == 1
    assert "'report-target' must be one of: 'comment', 'summary', 'both'." in result.stderr or (
        "'report-target' must be one of: 'comment', 'summary', 'both'." in result.stdout
    )
